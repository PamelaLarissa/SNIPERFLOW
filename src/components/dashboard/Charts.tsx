interface SourceChartProps {
  data: { source: string; count: number }[];
}

const COLORS = [
  'hsl(187 94% 43%)',
  'hsl(160 84% 39%)',
  'hsl(45 93% 47%)',
  'hsl(280 65% 60%)',
  'hsl(340 75% 55%)',
  'hsl(200 70% 50%)',
];

export const LeadsBySourceChart = ({ data }: SourceChartProps) => {
  return (
    <motion.div
      initial={{ opacity: 0, y: 20 }}
      animate={{ opacity: 1, y: 0 }}
      transition={{ duration: 0.5, delay: 0.6 }}
    >
      <Card variant="glass">
        <CardHeader>
          <CardTitle className="text-lg font-semibold">Leads por Fonte</CardTitle>
        </CardHeader>
        <CardContent className="p-3 sm:p-6">
          <div className="h-[220px] sm:h-[280px] flex items-center justify-center">
            <ResponsiveContainer width="100%" height="100%">
              <PieChart>
                <Pie
                  data={data}
                  cx="50%"
                  cy="50%"
                  innerRadius={45}
                  outerRadius={75}
                  paddingAngle={2}
                  dataKey="count"
                  nameKey="source"
                >
                  {data.map((_, index) => (
                    <Cell key={`cell-${index}`} fill={COLORS[index % COLORS.length]} />
                  ))}
                </Pie>
                <Tooltip
                  contentStyle={{
                    backgroundColor: 'hsl(var(--card))',
                    border: '1px solid hsl(var(--border))',
                    borderRadius: '8px',
                    color: 'hsl(var(--foreground))',
                  }}
                />
              </PieChart>
            </ResponsiveContainer>
          </div>
          <div className="flex flex-wrap justify-center gap-3 mt-4">
            {data.map((item, index) => (
              <div key={item.source} className="flex items-center gap-2 text-sm">
                <div 
                  className="w-3 h-3 rounded-full" 
                  style={{ backgroundColor: COLORS[index % COLORS.length] }}
                />
                <span className="text-muted-foreground">{item.source}</span>
              </div>
            ))}
          </div>
        </CardContent>
      </Card>
    </motion.div>
  );
};
